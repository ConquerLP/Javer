package ch.zhaw.it.pm4.javer.compiler;

import ch.zhaw.it.pm4.javer.compiler.ast.nodes.CompilationUnit;
import ch.zhaw.it.pm4.javer.compiler.codegen.CodeGeneratorFactory;
import ch.zhaw.it.pm4.javer.compiler.io.SourceFileReadException;
import ch.zhaw.it.pm4.javer.compiler.lexer.Lexer;
import ch.zhaw.it.pm4.javer.compiler.lexer.Token;
import ch.zhaw.it.pm4.javer.compiler.misc.SourceCache;
import ch.zhaw.it.pm4.javer.compiler.misc.diagnostics.DiagnosticBag;
import ch.zhaw.it.pm4.javer.compiler.misc.diagnostics.Severity;
import ch.zhaw.it.pm4.javer.compiler.parser.Parser;
import ch.zhaw.it.pm4.javer.compiler.visitor.*;

import java.util.List;
import java.util.stream.Collectors;

/**
 * Coordinates one complete compiler invocation from command-line options to
 * generated bytecode.
 */
public class Compiler {

    // Orchestrates the full compilation pipeline.
    //
    // Responsibilities:
    // - initialize context
    // - execute phases in order
    // - stop or continue pipeline based on diagnostics
    //
    // Pipeline:
    // args -> setup -> lexing -> parsing -> ast-checks -> code-generation -> done

    private final CompilerOptions options;
    private final CompilationContext context;
    private boolean phaseAbortRequested;

    /**
     * Creates a compiler configured for one source input and output target.
     *
     * @param options validated compiler options
     */
    public Compiler(CompilerOptions options) {
        this.options = options;
        SourceCache sourceCache = new SourceCache(options.getInputFilePath());
        this.context = new CompilationContext(
                new DiagnosticBag(options.getInputFilePath(), 50, CompilationPhase.COMPILER_SETUP, sourceCache),
                sourceCache);
        this.context.getDiagnosticBag().addPhaseAbortListener(phase -> phaseAbortRequested = true);
        enterPhase(CompilationPhase.ARGUMENT_PARSING);
    }

    /**
     * Parses command-line options and runs the compiler.
     *
     * @param args compiler command-line arguments
     */
    public static void main(String[] args) {
        System.setProperty("MODULE", "compiler");
        try {
            CompilerOptions options = CompilerOptions.create(args);
            Compiler compiler = new Compiler(options);
            compiler.compile();
            if (compiler.context.getDiagnosticBag().hasErrors()) {
                System.exit(1);
            }
        } catch (CompilerOptions.CompilerOptionException exception) {
            System.err.println(exception.getMessage());
            System.err.println(CompilerOptions.usage());
            System.exit(2);
        } catch (SourceFileReadException exception) {
            DiagnosticBag diagnostics = new DiagnosticBag(
                    exception.getFilePath(),
                    50,
                    CompilationPhase.COMPILER_SETUP,
                    null);
            diagnostics.add(null, Severity.ERROR, exception.getMessage());
            System.err.print(diagnostics.dumpReport());
            System.exit(1);
        }
    }

    private static void printSection(String title, String content) {
        System.out.println("=== " + title + " ===");
        System.out.println(content);
    }

    private static String dumpTokens(List<Token> tokens) {
        return tokens.stream()
                .map(Token::toString)
                .collect(Collectors.joining(System.lineSeparator()));
    }

    private static String dumpAst(CompilationUnit rootNode) {
        return new AstPrinter().printToString(rootNode);
    }

    private static String dumpSymbolTable(CompilationUnit rootNode) {
        return new SymbolTableAstPrinter().printToString(rootNode);
    }

    /**
     * Runs the compiler pipeline: lexing, parsing, symbol declaration, name
     * resolution, type checking, layout, semantic analysis, and code generation.
     */
    public void compile() {
        enterPhase(CompilationPhase.ARGUMENT_PARSING);

        List<Token> tokens = lex(context.getSourceCache().getSourceCode());
        if (stopAfterPhase()) {
            return;
        }
        if (options.isDumpLexer()) {
            printSection("LEXER TOKENS", dumpTokens(tokens));
        }

        CompilationUnit rootNode = parse(tokens);
        if (stopAfterPhase()) {
            return;
        }
        if (options.isDumpAst()) {
            printSection("AST", dumpAst(rootNode));
        }

        declareSymbols(rootNode);
        if (stopAfterPhase()) {
            return;
        }

        resolveNames(rootNode);
        if (stopAfterPhase()) {
            return;
        }
        if (options.isDumpSymbolTable()) {
            printSection("SYMBOL TABLE", dumpSymbolTable(rootNode));
        }
        typeCheck(rootNode);
        if (stopAfterPhase()) {
            return;
        }
        layout(rootNode);
        if (stopAfterPhase()) {
            return;
        }
        semanticAnalysis(rootNode);
        if (stopAfterPhase()) {
            return;
        }
        generateCode(rootNode);
        if (stopAfterPhase()) {
            return;
        }
        System.out.println("Compilation Successful");
    }

    private boolean stopOnErrors() {
        if (!context.getDiagnosticBag().hasErrors()) {
            return false;
        }

        System.err.print(context.getDiagnosticBag().dumpReport());
        return true;
    }

    private boolean stopAfterPhase() {
        if (stopOnPhaseAbort()) {
            return true;
        }
        return stopOnErrors();
    }

    private boolean stopOnPhaseAbort() {
        if (!phaseAbortRequested && !context.getDiagnosticBag().isPhaseAbortRequested()) {
            return false;
        }

        phaseAbortRequested = false;
        if (context.getDiagnosticBag().hasErrors()) {
            System.err.print(context.getDiagnosticBag().dumpReport());
        }
        return true;
    }

    private void enterPhase(CompilationPhase nextPhase) {
        phaseAbortRequested = false;
        context.getDiagnosticBag().setPhase(nextPhase);
    }

    private List<Token> lex(String sourceCode) {
        enterPhase(CompilationPhase.LEXING);
        Lexer lexer = new Lexer(sourceCode, context.getDiagnosticBag());
        return lexer.lexSourcecode();
    }

    private CompilationUnit parse(List<Token> tokens) {
        enterPhase(CompilationPhase.PARSING);
        return new Parser(tokens, context.getDiagnosticBag()).parse();
    }

    private void declareSymbols(CompilationUnit rootNode) {
        enterPhase(CompilationPhase.SYMBOL_TABLE_CREATION);
        new SymbolDeclarationVisitor(context.getDiagnosticBag()).visit(rootNode);
    }

    private void resolveNames(CompilationUnit node) {
        enterPhase(CompilationPhase.NAME_RESOLUTION);
        new NameResolutionVisitor(context.getDiagnosticBag()).visit(node);
    }

    private void typeCheck(CompilationUnit node) {
        enterPhase(CompilationPhase.TYPE_CHECKING);
        new TypeCheckVisitor(context.getDiagnosticBag()).visit(node);
    }

    private void layout(CompilationUnit node) {
        enterPhase(CompilationPhase.LAYOUT);
        new LayoutVisitor().visit(node);
    }

    private void semanticAnalysis(CompilationUnit node) {
        enterPhase(CompilationPhase.SEMANTIC_ANALYSIS);
        new SemanticChecker(context.getDiagnosticBag()).visit(node);
    }

    private void generateCode(CompilationUnit node) {
        enterPhase(CompilationPhase.CODE_GENERATION);
        CodeGeneratorFactory.create(
                options.getTarget(),
                context.getDiagnosticBag(),
                options.getOutputFilePath()).generate(node);
    }
}
